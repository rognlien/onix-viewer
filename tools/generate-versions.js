#!/usr/bin/env node
// tools/generate-versions.js
//
// Reads the version of every bundled data set from tools/data/ and emits
// Resources/versions.js, one small file the viewer can read on every page:
// the code-list issue, the Thema version, and the schema revision of each
// bundled ONIX release.
//
// The revision comes from the version attribute EDItEUR puts on <xs:schema>
// in each reference XSD: release.revision.correction, so 3.1.3.1 is
// revision 3.1.3 with one correction.
//
// Usage:
//   node tools/generate-versions.js

"use strict";

const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const DATA = path.join(__dirname, "data");
const CODELISTS_PATH = path.join(DATA, "onix-codelists.json");
const THEMA_PATH = path.join(DATA, "thema-codes.json");
const RELEASES = ["3.0", "3.1"];
const OUT_PATH = path.join(__dirname, "..", "Resources", "versions.js");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
}

function codeListIssue() {
  const table = readJson(CODELISTS_PATH).ONIXCodeTable;
  const issue = table && table.IssueNumber;
  if (!Number.isInteger(issue)) throw new Error(`${CODELISTS_PATH} states no code-list issue`);
  return issue;
}

function isoDate(yyyymmdd) {
  const digits = String(yyyymmdd);
  if (!/^\d{8}$/.test(digits)) throw new Error(`Thema date ${digits} is not YYYYMMDD`);
  return `${digits.slice(0, 4)}-${digits.slice(4, 6)}-${digits.slice(6, 8)}`;
}

function themaVersion() {
  const list = readJson(THEMA_PATH).CodeList;
  if (!list || list.IssueNumber == null || !list.LastUpdated) {
    throw new Error(`${THEMA_PATH} states no Thema version or date`);
  }
  return { version: String(list.IssueNumber), lastUpdated: isoDate(list.LastUpdated["#text"]) };
}

function schemaRevision(release) {
  const file = path.join(DATA, `ONIX_BookProduct_${release}_reference.xsd`);
  const parser = new (new JSDOM().window.DOMParser)();
  const schema = parser.parseFromString(fs.readFileSync(file, "utf8"), "application/xml").documentElement;
  const version = schema.localName === "schema" ? schema.getAttribute("version") || "" : "";
  const parts = version.split(".");
  if (parts.length < 3 || `${parts[0]}.${parts[1]}` !== release || !parts.every((part) => /^\d+$/.test(part))) {
    throw new Error(`${file} states no revision of ${release} on <xs:schema>; found version="${version}"`);
  }
  return parts.slice(0, 3).join(".");
}

function releases() {
  const revisions = {};
  for (const release of RELEASES) revisions[release] = { revision: schemaRevision(release) };
  return revisions;
}

function render(versions) {
  const lines = [
    "// versions.js — AUTO-GENERATED. Do not edit by hand.",
    "//",
    "// Generated by tools/generate-versions.js from tools/data/: the code-list",
    "// issue, the Thema version and the schema revision of each bundled release.",
    "",
    `window.OnixViewerVersions = ${JSON.stringify(versions, null, 2)};`,
    "",
  ];
  return lines.join("\n");
}

function main() {
  const versions = { codeLists: { issue: codeListIssue() }, thema: themaVersion(), releases: releases() };
  fs.writeFileSync(OUT_PATH, render(versions));
  const revisions = RELEASES.map((release) => versions.releases[release].revision).join(", ");
  console.log(`Wrote ${path.relative(process.cwd(), OUT_PATH)} — Issue ${versions.codeLists.issue}, ` +
    `Thema ${versions.thema.version}, ${revisions}`);
}

main();
